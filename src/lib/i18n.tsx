export type MessageKey = keyof typeof messages.zh;

function interpolate(message: string, vars?: Record<string, string | number>) {
  if (!vars) return message;
  return message.replace(/\{(\w+)\}/g, (token, key: string) => (Object.hasOwn(vars, key) ? String(vars[key]) : token));
}

const Ctx = createContext<I18n | null>(null);

export function LocaleProvider({
  locale,
  prefixed = true,
  children,
}: {
  locale: Locale;
  prefixed?: boolean;
  children: ReactNode;
}) {
  const prefix = prefixed ? `/${locale}` : '';
  useEffect(() => {
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
  }, [locale]);
  return (
    <Ctx.Provider
      value={{
        locale,
        pathFor: (path) => `${prefix}${path === '/' ? '' : path}`,
        t: (key, vars) => interpolate(messages[locale][key], vars),
      }}
    >
      {children}
    </Ctx.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error('useI18n must be used within LocaleProvider');
  return ctx;
}
