type MessageKeyParity = [
  | Exclude<keyof (typeof messages)['zh'], keyof (typeof messages)['en']>
  | Exclude<keyof (typeof messages)['en'], keyof (typeof messages)['zh']>,
] extends [never]
  ? true
  : never;

